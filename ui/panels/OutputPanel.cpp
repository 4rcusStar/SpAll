// OutputPanel.cpp — statistics tree, log view and hex dump.
#include "OutputPanel.h"

#include <QFontDatabase>
#include <QHeaderView>
#include <QPlainTextEdit>
#include <QTabWidget>
#include <QTreeWidget>
#include <QVBoxLayout>

#include <algorithm>

namespace spall {

namespace {

/// Top-N opcode rows to show.
constexpr int kTopInstructionCount = 20;

}  // namespace

OutputPanel::OutputPanel(QWidget* parent) : QWidget(parent) {
    auto* layout = new QVBoxLayout(this);
    layout->setContentsMargins(0, 0, 0, 0);

    m_tabs = new QTabWidget(this);

    QFont mono = QFontDatabase::systemFont(QFontDatabase::FixedFont);
    mono.setPointSize(10);

    // --- statistics ---------------------------------------------------------
    m_statsTree = new QTreeWidget(this);
    m_statsTree->setColumnCount(2);
    m_statsTree->setHeaderLabels({tr("Item"), tr("Value")});
    m_statsTree->setRootIsDecorated(false);
    m_statsTree->setAlternatingRowColors(true);
    m_statsTree->header()->setSectionResizeMode(1, QHeaderView::Stretch);
    m_statsTree->setFont(mono);
    m_tabs->addTab(m_statsTree, tr("Stats"));

    // --- log ----------------------------------------------------------------
    m_logView = new QPlainTextEdit(this);
    m_logView->setReadOnly(true);
    m_logView->setFont(mono);
    m_logView->setPlaceholderText(tr("Compiler / validator / optimizer messages appear here."));
    m_tabs->addTab(m_logView, tr("Log"));

    // --- binary -------------------------------------------------------------
    m_binaryView = new QPlainTextEdit(this);
    m_binaryView->setReadOnly(true);
    m_binaryView->setFont(mono);
    m_binaryView->setLineWrapMode(QPlainTextEdit::NoWrap);
    m_binaryView->setPlaceholderText(tr("Hex dump of the optimized SPIR-V module."));
    m_tabs->addTab(m_binaryView, tr("Binary"));

    layout->addWidget(m_tabs);
}

void OutputPanel::retranslate() {
    m_tabs->setTabText(0, tr("Stats"));
    m_tabs->setTabText(1, tr("Log"));
    m_tabs->setTabText(2, tr("Binary"));
    m_statsTree->setHeaderLabels({tr("Item"), tr("Value")});
    m_logView->setPlaceholderText(tr("Compiler / validator / optimizer messages appear here."));
    m_binaryView->setPlaceholderText(tr("Hex dump of the optimized SPIR-V module."));

    // The statistics rows and the hex dump are regenerated by the next setStatistics()
    // / setBinary() call.
}

void OutputPanel::showTab(int index) {
    if (index >= 0 && index < m_tabs->count()) {
        m_tabs->setCurrentIndex(index);
    }
}

void OutputPanel::setStatistics(const SpirvStats& stats,
                                const SpirvStats& statsBeforeOptimization,
                                OptimizationLevel level,
                                qint64 compileMs) {
    m_statsTree->clear();

    const auto add = [this](const QString& key, const QString& value) {
        auto* item = new QTreeWidgetItem(m_statsTree);
        item->setText(0, key);
        item->setText(1, value);
    };

    add(tr("Compile time"), QStringLiteral("%1 ms").arg(compileMs));
    add(tr("SPIR-V version"), QStringLiteral("0x%1").arg(stats.version, 8, 16, QLatin1Char('0')));
    add(tr("Optimization level"), optimizationLevelName(level));
    add(tr("Words (before optimization)"), QString::number(statsBeforeOptimization.wordCount));
    add(tr("Words (after optimization)"), QString::number(stats.wordCount));
    add(tr("Instructions (before optimization)"),
        QString::number(statsBeforeOptimization.instructionCount));
    add(tr("Instructions (after optimization)"), QString::number(stats.instructionCount));
    add(tr("id bound"), QString::number(stats.idBound));

    const qint64 delta = static_cast<qint64>(stats.wordCount) -
                         static_cast<qint64>(statsBeforeOptimization.wordCount);
    if (delta != 0) {
        add(tr("Word delta"),
            QStringLiteral("%1%2")
                .arg(delta > 0 ? QStringLiteral("+") : QString())
                .arg(delta));
    }

    // Top opcodes by frequency.
    QVector<QPair<QString, quint32>> counts;
    counts.reserve(stats.opcodeCounts.size());
    for (auto it = stats.opcodeCounts.constBegin(); it != stats.opcodeCounts.constEnd(); ++it) {
        counts.append({it.key(), it.value()});
    }
    std::sort(counts.begin(), counts.end(), [](const auto& a, const auto& b) {
        if (a.second != b.second) {
            return a.second > b.second;
        }
        return a.first < b.first;
    });

    auto* root = new QTreeWidgetItem(m_statsTree);
    root->setText(0, tr("Top %1 opcodes by frequency").arg(kTopInstructionCount));
    root->setText(1, tr("opcode kinds: %1").arg(counts.size()));
    root->setExpanded(true);
    const int limit = std::min(kTopInstructionCount, static_cast<int>(counts.size()));
    for (int i = 0; i < limit; ++i) {
        auto* item = new QTreeWidgetItem(root);
        item->setText(0, counts.at(i).first);
        item->setText(1, QString::number(counts.at(i).second));
    }
    m_statsTree->expandAll();
}

void OutputPanel::setLog(const QString& text) {
    m_logView->setPlainText(text);
}

void OutputPanel::setBinary(const QVector<quint32>& words) {
    if (words.isEmpty()) {
        m_binaryView->setPlainText(QString());
        return;
    }

    QStringList lines;
    lines.reserve(words.size() / 4 + 2);
    lines << tr("; words: %1, bytes: %2").arg(words.size()).arg(words.size() * 4);
    lines << QStringLiteral("; offset      0        1        2        3");

    for (int i = 0; i < words.size(); i += 4) {
        QString line = QStringLiteral("%1  ").arg(i * 4, 8, 16, QLatin1Char('0'));
        for (int j = 0; j < 4; ++j) {
            if (i + j < words.size()) {
                line += QStringLiteral("%1 ").arg(words.at(i + j), 8, 16, QLatin1Char('0'));
            } else {
                line += QStringLiteral("         ");
            }
        }
        lines << line;
    }
    m_binaryView->setPlainText(lines.join(QLatin1Char('\n')));
}

}  // namespace spall
